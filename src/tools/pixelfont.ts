export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Width in pixels of `text` at `scale` (1px spacing between glyphs). */
export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * (GLYPH_W + 1) - 1) * scale;
}

/** Draw crisp pixel text. `shadow` draws a 1-scale-px drop shadow first. */
export function drawText(
  g: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  shadow?: string,
): void {
  if (shadow) drawText(g, text, x + scale, y + scale, shadow, scale);
  g.fillStyle = color;
  x = Math.round(x);
  y = Math.round(y);
  let cx = x;
  for (const ch of text) {
    const glyph = G[ch] ?? G[ch.toUpperCase()] ?? G['?'];
    for (let r = 0; r < GLYPH_H; r++) {
      const row = glyph[r];
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === '#') g.fillRect(cx + c * scale, y + r * scale, scale, scale);
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}

export function drawTextCentered(
  g: CanvasRenderingContext2D,
  text: string,
  cx: number,
  y: number,
  color: string,
  scale = 1,
  shadow?: string,
): void {
  drawText(g, text, cx - textWidth(text, scale) / 2, y, color, scale, shadow);
}

/** Greedy word-wrap to a max character count per line. */
export function wrapText(text: string, maxChars: number): string[] {
  const out: string[] = [];
  let cur = '';
  for (const w of text.split(/\s+/)) {
    if (!w) continue;
    if ((cur ? cur.length + 1 : 0) + w.length > maxChars) {
      if (cur) out.push(cur);
      cur = w;
    } else cur = cur ? cur + ' ' + w : w;
  }
  if (cur) out.push(cur);
  return out;
}
